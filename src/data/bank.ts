// ---------------- helpers ----------------
export const BANK_BY_COURSE = (course: string) => BANK.filter((q) => q.course === course);
export const COURSES_IN_BANK = Array.from(new Set(BANK.map((q) => q.course)));

export interface BankFilters {
  course?: string;
  unit?: number;
  topic?: string;
  difficulty?: string;
  type?: string;
  conceptId?: string;
  onlyUnseen?: boolean;
  onlyMissed?: boolean;
  weakAreas?: boolean;
}

export function filterBank(f: BankFilters, seen: Set<string>, missed: Set<string>): BankQuestion[] {
  return BANK.filter((q) => {
    if (f.course && q.course !== f.course) return false;
    if (f.unit !== undefined && q.unit !== f.unit) return false;
    if (f.topic && q.topic !== f.topic) return false;
    if (f.difficulty && q.difficulty !== f.difficulty) return false;
    if (f.type && q.type !== f.type) return false;
    if (f.conceptId && q.conceptId !== f.conceptId) return false;
    if (f.onlyUnseen && seen.has(q.id)) return false;
    if (f.onlyMissed && !missed.has(q.id)) return false;
    return true;
  });
}
