export const UNITS_BY_COURSE: Record<CourseId, Unit[]> = {
  p1: UNITS.filter((u) => u.course === "p1"),
  p2: UNITS.filter((u) => u.course === "p2"),
  cm: UNITS.filter((u) => u.course === "cm"),
  cem: UNITS.filter((u) => u.course === "cem"),
};

export function coursesForConcept(conceptId: string): CourseId[] {
  const concept = CONCEPT_MAP[conceptId];
  if (!concept) return [];
  return [concept.courseId];
}

/** Concepts that list this concept as a prerequisite (dependents). */
export function dependentsOf(conceptId: string): Concept[] {
  return CONCEPTS.filter((c) => c.prereqs.includes(conceptId));
}

export function searchCurriculum(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return { concepts: [], units: [] };
  const concepts = CONCEPTS.filter((c) =>
    c.name.toLowerCase().includes(q) ||
    c.tagline.toLowerCase().includes(q) ||
    c.intuition.toLowerCase().includes(q) ||
    c.recognition.toLowerCase().includes(q) ||
    c.equations.some((e) => e.label.toLowerCase().includes(q) || e.where.toLowerCase().includes(q)) ||
    c.mistakes.some((m) => m.wrong.toLowerCase().includes(q)),
  );
  const units = UNITS.filter((u) => u.name.toLowerCase().includes(q) || u.blurb.toLowerCase().includes(q));
  return { concepts, units };
}

